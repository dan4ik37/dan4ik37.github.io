// Подпись результата для ссылки-вызова /games/<id>?s=<очки>&n=<ник> — как gameBestLabel() в js/features/games.js
const ru = (n, one, few, many) => n % 10 === 1 && n % 100 !== 11 ? one : [2, 3, 4].includes(n % 10) && ![12, 13, 14].includes(n % 100) ? few : many;
export function scoreLabel(id, s){
  switch (id) {
    case 'reaction': return `реакцию ${1000 - s} мс`;
    case 'guess':    return `${s} из 10`;
    case 'cities':   return `цепочку из ${s} ${ru(s, 'города', 'городов', 'городов')}`;
    case 'ttt':      return s >= 2 ? 'победу над непобедимым ботом' : 'ничью с непобедимым ботом';
    case 'checkers': return `победу с ${s} ${ru(s, 'шашкой', 'шашками', 'шашками')}`;
    case 'sea':      return `победу с ${s} ${ru(s, 'уцелевшей палубой', 'уцелевшими палубами', 'уцелевшими палубами')}`;
    case 'words':    return `с ${7 - s}-й попытки`;
    case 'snake':    return `${s} ${ru(s, 'яблоко', 'яблока', 'яблок')}`;
    default:         return `${s.toLocaleString('ru')} ${ru(s, 'очко', 'очка', 'очков')}`;
  }
}
