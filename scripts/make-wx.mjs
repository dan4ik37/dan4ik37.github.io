// Biome weather data → js/engine/wx.js (T-135, BIOME_WEATHER.md v2 WX0/WX1): node scripts/make-wx.mjs
// Reads data/wx/weather_events.csv, climate_classes.csv, wx_levels.csv (Layer-1 tables, append-only) and rewrites the block
// between "// <wx-data>" and "// </wx-data>" in js/engine/wx.js: the CSV lines as strings (parsed once at load by WX.parseRow,
// the same parser mods use) and the integer cosine tables of T_q (COSQ128: season term by phase, COSQ24: day term by hour) as
// literals, so no engine's Math.cos can move a value. `--check` exits 1 when wx.js is not up to date (CI).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const SITE = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = f => fs.readFileSync(path.join(SITE, 'data/wx', f), 'utf8').split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith('#'));
const ev = rd('weather_events.csv'), cl = rd('climate_classes.csv'), lv = rd('wx_levels.csv');
const body = l => l.slice(1);   // drop the header line
for (const l of body(ev)) if (l.split(',').length !== 30) throw new Error('weather_events.csv: 30 columns needed: ' + l.slice(0, 60));
const ids = body(ev).map(l => +l.split(',')[0]);
ids.forEach((id, i) => { if (id !== i + 1) throw new Error('weather_events.csv: ids must be dense from 1, got ' + id + ' at ' + (i + 1)); });
const cos128 = Array.from({ length: 128 }, (_, i) => Math.round(1000 * Math.cos(2 * Math.PI * (i / 32 - 1.5) / 4)));
const cos24 = Array.from({ length: 24 }, (_, h) => Math.round(1000 * Math.cos(2 * Math.PI * (h - 15) / 24)));
const js = a => '[\n' + a.map(l => '    ' + JSON.stringify(l) + ',').join('\n') + '\n  ]';
const block = `// <wx-data> generated by scripts/make-wx.mjs from data/wx/*.csv — do not edit by hand
  const CSV_EVENTS = ${js(body(ev))};
  const CSV_CLASSES = ${js(body(cl))};
  const CSV_LEVELS = ${js(body(lv))};
  const COSQ128 = [${cos128.join(', ')}];
  const COSQ24 = [${cos24.join(', ')}];
  // </wx-data>`;
const F = path.join(SITE, 'js/engine/wx.js'), src = fs.readFileSync(F, 'utf8');
const a = src.indexOf('// <wx-data>'), b = src.indexOf('// </wx-data>');
if (a < 0 || b < 0) throw new Error('wx.js: no <wx-data> block');
const CR = String.fromCharCode(13), LFc = String.fromCharCode(10), CRLF = CR + LFc;   // Windows checkouts keep CRLF
const NL = src.includes(CRLF) ? CRLF : LFc, lf = t => t.split(CRLF).join(LFc);
const out = src.slice(0, a) + block.split(LFc).join(NL) + src.slice(b + '// </wx-data>'.length);
if (process.argv.includes('--check')) { if (lf(out) !== lf(src)) { console.log('wx.js is out of date: run node scripts/make-wx.mjs'); process.exit(1); } console.log('wx.js data up to date'); }
else { fs.writeFileSync(F, out); console.log('wx.js: ' + body(ev).length + ' events, ' + body(cl).length + ' classes, ' + body(lv).length + ' level rows'); }
