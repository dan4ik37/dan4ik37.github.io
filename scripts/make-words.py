nouns, allw = set(), set()
with open(DIC, encoding='utf8') as f:
    next(f)
    for line in f:
        raw = line.strip()
        if not raw: continue
        w0, _, fl = raw.partition('/')
        if not re.fullmatch(r'[а-яё]+', w0): continue   # с большой буквы (имена, города) и с дефисом — мимо
        w = norm(w0)
        allw.add(w)
        fs = set(fl)
        if 'A' in fs: continue
        ok = bool(fs & NOUN_FLAGS) or (fs == {'E'} and not w.endswith(('ее', 'ей')))
        if not ok: continue
        if 'O' in fs and w[-1] in 'ыиая' and w not in PLURAL: continue   # формы мн. ч. («вёсны», «зайцы»)
        nouns.add(w)
nouns |= {w for w in INDECL | IRREG if w in allw} | PLURAL | SUBST
