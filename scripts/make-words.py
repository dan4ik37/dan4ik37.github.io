EXTRA = ['стрим', 'донат']   # слова канала: в словаре 2008 года их нет, но для сайта стримера — свои

def norm(w): return w.lower().replace('ё', 'е')

allowed = set()
lic = ''
with open(DIC, encoding='utf8') as f:
    next(f)   # первая строка — число слов
    for line in f:
        w = norm(line.split('/')[0].strip())
        if re.fullmatch(r'[а-я]{5}', w) and line[0].islower():
            allowed.add(w)

answers, dropped = [], []
for w in dict.fromkeys(norm(x) for x in ANSWERS_RAW):
    if len(w) != 5: dropped.append(w); continue
    if w in allowed or w in EXTRA: answers.append(w)
    else: dropped.append(w)
answers += [w for w in EXTRA if w not in answers]
allowed |= set(answers)

# Порядок слов дня — перемешан фиксированным зерном (одинаково у всех). Пересборка с другим списком меняет
# порядок — слово «сегодняшнего» дня тоже может смениться; игра это переживает (прогресс хранится вместе со словом).
random.Random(37).shuffle(answers)

with open(OUT, 'w', encoding='utf8') as f:
    f.write('// Данные игры «5 букв» — собрано scripts/make-words.py, вручную не править.\n')
    f.write('// ALLOWED — 5-буквенные слова из словаря ru_RU (npm dictionary-ru), лицензия BSD-3-Clause:\n')
