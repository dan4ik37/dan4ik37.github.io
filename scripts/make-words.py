    f.write('// ANSWERS — загадываемые слова (свой список). Порядок = порядок слов дня: менять только дописыванием в конец.\n')
    f.write('window.WORDS5 = {\n')
    f.write('  answers: ' + json.dumps(answers, ensure_ascii=False) + ',\n')
    f.write("  allowed: '" + ''.join(sorted(allowed)) + "',\n")
    f.write('};\n')
