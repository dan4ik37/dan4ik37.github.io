def front(words):
    # сжатие «общим началом»: цифра — сколько первых букв взять у предыдущего слова (0–9), дальше — остаток слова
    out, prev = [], ''
    for w in words:
        k = 0
        while k < 9 and k < len(prev) and k < len(w) and prev[k] == w[k]: k += 1
        out.append(str(k) + w[k:]); prev = w
    return ''.join(out)

