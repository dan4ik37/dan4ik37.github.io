#!/usr/bin/env bash
# Creates server/.env with fresh random secrets — ON THE SERVER only (docs/SERVER.md). The file never goes to git
# (.gitignore: .env) and the secrets are never printed. Usage (from this folder):
#   bash make-env.sh <public IP of the server>
# Running it again with a new IP only updates the addresses and keeps the secrets.
set -eu
cd "$(dirname "$0")"
IP="${1:-}"
if ! printf '%s' "$IP" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}$'; then
  echo "Нужен публичный IP сервера, например:  bash make-env.sh 203.0.113.7"
  exit 1
fi
# внутренний адрес машины (Oracle: 10.0.0.x) — с него coturn принимает и пересылает, наружу говорит публичный
PRIV="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i <= NF; i++) if ($i == "src") { print $(i + 1); exit }}')"
[ -n "$PRIV" ] || PRIV="$(hostname -I | awk '{print $1}')"
if [ -f .env ]; then
  sed -i -e "s/^RT_HOST=.*/RT_HOST=$IP/" -e "s/^TURN_PUBLIC_IP=.*/TURN_PUBLIC_IP=$IP/" -e "s/^TURN_PRIVATE_IP=.*/TURN_PRIVATE_IP=$PRIV/" .env
  echo "Адреса в .env обновлены (публичный $IP, внутренний $PRIV), секреты прежние."
  exit 0
fi
umask 077
{
  echo "# d37 server settings — generated by make-env.sh on $(date -u +%F). Secrets: do not copy anywhere, do not show."
  echo "RT_HOST=$IP"
  echo "TURN_PUBLIC_IP=$IP"
  echo "TURN_PRIVATE_IP=$PRIV"
  echo "TURN_SECRET=$(openssl rand -hex 32)"
  echo "ADMIN_TOKEN=$(openssl rand -hex 24)"
} > .env
chmod 600 .env
echo "Готово: .env создан (секреты внутри, на экран не выводятся). Публичный IP: $IP, внутренний: $PRIV"
