-- 1. Новое поле. default now() — на будущее: у всех НОВЫХ регистраций
--    (через триггер handle_new_user из registration.sql) дата
--    проставится сама, без изменения самого триггера.
alter table public.profiles
  add column if not exists created_at timestamptz default now();

-- 2. Бэкфилл для уже существующих аккаунтов — на шаге 1 всем сразу
--    проставилось "время выполнения этого ALTER", это не настоящая
--    дата регистрации. Настоящая дата лежит в auth.users, и достать
--    её можно только отсюда, из SQL Editor (обычный клиент/RLS к
--    auth.users доступа не имеет — это правильно, там email и прочее).
--    Безопасно выполнять повторно.
update public.profiles p
set created_at = u.created_at
from auth.users u
where p.id = u.id;

