    + '.rd-next{align-self:center;padding:.45rem 1.2rem;border-radius:999px;border:0;background:#ffc233;color:#222;font:700 .9rem system-ui,sans-serif;cursor:pointer}'
    + '.rd-next[hidden]{display:none}'
    + 'body.low .rd-time i{transition:none}';

  function build(G){
    if (!document.getElementById('rdCss')) { const st = document.createElement('style'); st.id = 'rdCss'; st.textContent = CSS; document.head.appendChild(st); }
    let h = '<div class="rd"><div class="rd-top"><span class="rd-n"></span><div class="rd-time"><i></i></div><span class="rd-s"></span></div><div class="rd-q"></div><div class="rd-a">';
    for (let a = 0; a < 4; a++) h += '<button type="button" class="rd-b" data-k="' + a + '"><b>' + (a + 1) + '</b><span></span></button>';
    G.host.innerHTML = h + '</div><div class="rd-why"></div><button type="button" class="rd-next" data-k="' + NEXT + '" hidden>Дальше ▶</button></div>';
    const B = G.box = G.host.firstChild;
    G.n = B.querySelector('.rd-n'); G.time = B.querySelector('.rd-time'); G.sec = B.querySelector('.rd-s');
    G.q = B.querySelector('.rd-q'); G.btns = B.querySelectorAll('.rd-b'); G.why = B.querySelector('.rd-why'); G.next = B.querySelector('.rd-next');
    G.qi = -1;
  }

  function draw(G, s){
    const qi = Math.min(s.qi, N - 1), Q = QS[s.order[qi]];
    if (G.qi !== qi) {
      G.qi = qi;
      G.q.textContent = Q[0];
      for (let a = 0; a < 4; a++) G.btns[a].lastChild.textContent = Q[1][s.perm[4 * qi + a]];
    }
    const reveal = s.phase === 1 || s.over;
    for (let a = 0; a < 4; a++) {
      G.btns[a].classList.toggle('ok', reveal && a === s.good);
      G.btns[a].classList.toggle('no', reveal && a === s.pick && a !== s.good);
      G.btns[a].disabled = reveal;
    }
    G.n.textContent = (qi + 1) + '/' + N;
    G.sec.textContent = Math.ceil(s.left / 60) + ' с';
    G.time.firstChild.style.width = (100 * s.left / QT).toFixed(1) + '%';
    G.time.classList.toggle('lo', s.left < 5 * 60);
    G.why.textContent = reveal ? (s.pick === s.good ? 'Верно! +' + s.gain + '. ' : s.pick < 0 ? 'Время вышло. ' : 'Не угадал. ') + Q[2] : '';
    G.next.hidden = s.phase !== 1 || s.over;
  }

