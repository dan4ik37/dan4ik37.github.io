  function create(rng){
    const s = { rng, qi: 0, left: QT, phase: 0, wait: 0, pick: -1, good: -1, gain: 0, score: 0, right: 0, fast: 0,
      over: false, v: 0, snd: 0, order: new Uint8Array(N), perm: new Uint8Array(4 * N), pool: new Uint8Array(QS.length) };
    // 10 разных вопросов (Фишер–Йетс на rng) и порядок ответов у каждого
    const P = s.pool;
    for (let i = 0; i < QS.length; i++) P[i] = i;
    for (let i = QS.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)), t = P[i]; P[i] = P[j]; P[j] = t; }
    for (let q = 0; q < N; q++) {
      s.order[q] = P[q];
      for (let a = 0; a < 4; a++) s.perm[4 * q + a] = a;
      for (let a = 3; a > 0; a--) { const j = Math.floor(rng() * (a + 1)), t = s.perm[4 * q + a]; s.perm[4 * q + a] = s.perm[4 * q + j]; s.perm[4 * q + j] = t; }
    }
    s.good = goodAt(s, 0);
    return s;
  }
  // на какой кнопке (0…3) верный ответ вопроса q (верный — нулевой в QS)
  function goodAt(s, q){ for (let a = 0; a < 4; a++) if (s.perm[4 * q + a] === 0) return a; return 0; }

  function next(s){
    s.qi++; s.v++;
    if (s.qi >= N) { s.over = true; s.snd = s.right >= 7 ? 'win' : 'ok'; return; }
    s.phase = 0; s.left = QT; s.pick = -1; s.gain = 0; s.good = goodAt(s, s.qi);
  }

  function answer(s, a){
    s.phase = 1; s.wait = SHOW; s.pick = a; s.v++;
    if (a === s.good) {
      const sec = Math.ceil(s.left / 60);
      s.gain = 50 + 4 * sec; s.score += s.gain; s.right++;
      if (sec >= 10) s.fast++;
      s.snd = 'ok';
    } else { s.gain = 0; s.snd = 'bad'; }
  }

  function input(s, e){
    if (s.over || (e.type !== T.PICK && e.type !== T.KEY)) return;
    const k = e.k;
    if (s.phase === 1) { if (k === NEXT && s.wait < SHOW - GUARD) next(s); return; }
    if (k >= 0 && k < 4) answer(s, k);
  }

  function step(s){
    if (s.over) return;
    if (s.phase === 1) { if (!--s.wait) next(s); return; }
    if (--s.left <= 0) { s.left = 0; answer(s, -1); return; }
    if (s.left % 60 === 0) s.v++;   // полоска времени — раз в секунду
  }

