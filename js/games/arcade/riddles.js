    + '.rd-a{display:grid;gap:.5rem}'
    + '.rd-b{text-align:left;min-height:48px;padding:.6rem .9rem;border-radius:12px;border:2px solid rgba(255,255,255,.14);background:rgba(255,255,255,.06);color:#eef;'
