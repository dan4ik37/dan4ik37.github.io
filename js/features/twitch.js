// БАГ ИСПРАВЛЕН: раньше здесь был fetch(...,{mode:'no-cors'}) для проверки
// live-статуса. В no-cors режиме JS не видит код ответа — promise почти
// всегда резолвится, даже если стрим НЕ идёт. Из-за этого сайт ВСЕГДА
// показывал "🔴 Стрим идёт прямо сейчас!" и, что хуже, каждые 3 минуты
// (setInterval) переприсваивал src у чата — а это форсит полную
// перезагрузку iframe. Поэтому твич-чат постоянно сбрасывался сам по себе.
//
// Настоящая проверка live-статуса требует Twitch Helix API через
// серверную функцию (по аналогии с /api/donations для DonationAlerts) —
// нужны client_id/secret с dev.twitch.tv, которых пока нет в проекте.
// Сделать можно отдельно, если нужно показывать бейдж "точно в эфире".
//
// Пока — честный вариант: плеер и чат Twitch встроены на странице
// ВСЕГДА (без надписи "идёт прямо сейчас"), src ставится один раз при
// загрузке. Сам виджет Twitch показывает офлайн-заглушку, если эфира нет —
// это уже встроено в сам плеер/чат Twitch, ничего изобретать не нужно.
//
// ОПТИМИЗАЦИЯ: src ставим не всегда сразу, а только когда реально открыта
// #/home — см. initHomeMedia() и хук в showPage() ниже. Если открыли сайт
// сразу по ссылке на #/chat или #/poll, твич-плеер грузиться не будет.
let homeMediaLoaded = false;
function initHomeMedia(){
  if (homeMediaLoaded) return;
  homeMediaLoaded = true;
  document.getElementById('autoStreamPlayer').src = `https://player.twitch.tv/?channel=${TWITCH}&parent=${HOST}&autoplay=false`;
  loadYT();
}
